-- TABLA DE SOLICITUDES
CREATE TABLE job_solicitudes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR2(150) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_proceso TIMESTAMP,

    CONSTRAINT chk_job_solicitudes_estado
        CHECK (estado IN ('PENDIENTE', 'PROCESADO'))
);

COMMIT;

-- TABLA DE HISTORIAL
CREATE TABLE job_log (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_ejecucion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    registros_procesados NUMBER DEFAULT 0 NOT NULL,
    mensaje VARCHAR2(1000)
);

COMMIT;

-- PROCEDIMIENTO PARA REGISTRAR ERRORES
CREATE OR REPLACE PROCEDURE pr_registrar_error (
    p_mensaje IN VARCHAR2
)
AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN

    INSERT INTO job_log (
        fecha_ejecucion,
        registros_procesados,
        mensaje
    )
    VALUES (
        SYSTIMESTAMP,
        0,
        SUBSTR(p_mensaje, 1, 1000)
    );

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

COMMIT;

-- PROCEDIMIENTO PRINCIPAL.
CREATE OR REPLACE PROCEDURE pr_procesar_solicitudes AS

    v_total NUMBER := 0;
    v_error VARCHAR2(1000);

BEGIN

    -- Actualizar solicitudes pendientes
    UPDATE job_solicitudes
       SET estado = 'PROCESADO',
           fecha_proceso = SYSTIMESTAMP
     WHERE estado = 'PENDIENTE';

    -- Obtener registros procesados
    v_total := SQL%ROWCOUNT;

    -- Registrar ejecución
    INSERT INTO job_log (
        fecha_ejecucion,
        registros_procesados,
        mensaje
    )
    VALUES (
        SYSTIMESTAMP,
        v_total,
        'Procesamiento finalizado correctamente'
    );

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN

        -- Capturar error original
        v_error := SUBSTR(SQLERRM, 1, 1000);

        -- Revertir operación principal
        ROLLBACK;

        -- Registrar error independientemente
        pr_registrar_error('ERROR: ' || v_error);

        -- Propagar excepción
        RAISE;

END;
/

COMMIT;

-- CREACIÓN DEL JOB: QUEDA DESHABILITADO INICIALMENTE.
BEGIN

    DBMS_SCHEDULER.CREATE_JOB(
        job_name        => 'JOB_PROCESAR_SOLICITUDES',
        job_type        => 'STORED_PROCEDURE',
        job_action      => 'PR_PROCESAR_SOLICITUDES',
        start_date      => SYSTIMESTAMP,
        repeat_interval => 'FREQ=MINUTELY;INTERVAL=5',
        enabled         => FALSE,
        auto_drop       => FALSE,
        comments        => 'Procesa solicitudes pendientes cada cinco minutos'
    );

END;
/

COMMIT;

